package handlers

import (
	"regexp"
	"strings"
)

// PCPartPicker shows lists only to signed-in users, so Racket can't fetch
// them. Instead the user copies a list's plain-text markup (Markup, then the
// Text tab, on the list page) and pastes it. It looks like this:
//
//	PCPartPicker Part List: https://pcpartpicker.com/list/Kd3LPf
//
//	CPU: AMD Ryzen 7 9800X3D 4.7 GHz 8-Core Processor  ($444.00 @ Amazon)
//	Memory: Corsair Vengeance RGB 32 GB (2 x 16 GB) DDR5-6000 CL36 Memory  ($579.99 @ Corsair)
//	Total: $3965.72
//	Prices include shipping, taxes, and discounts when available
//	Generated by PCPartPicker 2026-10-02 21:28 EDT-0400

var (
	// pcppListURLRe finds a list URL, on any regional subdomain, and its ID.
	pcppListURLRe = regexp.MustCompile(`(?i:https?://(?:[a-z0-9-]+\.)?pcpartpicker\.com/list/)([A-Za-z0-9]+)`)

	// pcppPartRe splits a part line into its type and the rest. Only
	// pcppPartTypes are parts. The colon must be followed by a space, so
	// "Generated by PCPartPicker 2026-10-02 21:28" isn't a part.
	pcppPartRe = regexp.MustCompile(`^([A-Za-z][A-Za-z0-9 /&+-]*):\s+(.+)$`)

	// pcppPriceRe matches the trailing price, "($444.00 @ Amazon)" or
	// "(Purchased For $50.00)". A name's own brackets, like "(2 x 16 GB)",
	// have no currency symbol and stay part of the name.
	pcppPriceRe = regexp.MustCompile(`\s*\(([^()]*[$£€¥₹][^()]*)\)$`)
)

// pcppPartTypes are PCPartPicker's part types, by matchKey. Other
// "Label: value" lines, like "Total: $3965.72" or a note someone added to
// the paste, aren't parts.
//
//nolint:goconst // PCPartPicker's type names, also keys in other tables
var pcppPartTypes = map[string]bool{
	"cpu": true, "cpu cooler": true, "motherboard": true, "memory": true, "storage": true,
	"video card": true, "case": true, "power supply": true, "operating system": true,
	"monitor": true, "sound card": true, "wired network adapter": true,
	"wireless network adapter": true, "headphones": true, "keyboard": true, "mouse": true,
	"speakers": true, "webcam": true, "case accessory": true, "case fan": true,
	"fan controller": true, "thermal compound": true, "external storage": true,
	"optical drive": true, "ups": true, "custom": true,
}

// pcppListURL returns the canonical URL (https://pcpartpicker.com/list/ID)
// of the list URL in s, or "" if there's none. Regional sites, http, and
// anything after the ID all name the same list.
func pcppListURL(s string) string {
	m := pcppListURLRe.FindStringSubmatch(s)
	if m == nil {
		return ""
	}
	return "https://pcpartpicker.com/list/" + m[1]
}

// purchasedFor starts the price of a part the list's owner marked bought.
const purchasedFor = "Purchased For "

// pcppList is a pasted PCPartPicker list: the list's canonical URL from
// its first line ("" if the paste didn't include it) and its parts, in
// order.
type pcppList struct {
	url  string
	rows []csvRow
}

// parsePCPPText parses PCPartPicker's plain-text list markup. Lines it
// doesn't recognize are skipped, so a paste with extra text still works.
func parsePCPPText(text string) pcppList {
	var list pcppList
	for line := range strings.Lines(text) {
		line = strings.TrimSpace(line)
		if strings.HasPrefix(strings.ToLower(line), "pcpartpicker part list") {
			list.url = pcppListURL(line)
			continue
		}
		m := pcppPartRe.FindStringSubmatch(line)
		if m == nil || !pcppPartTypes[matchKey(m[1])] {
			continue
		}
		row := csvRow{category: m[1], name: m[2]}
		if loc := pcppPriceRe.FindStringSubmatchIndex(row.name); loc != nil {
			price, merchant, _ := strings.Cut(row.name[loc[2]:loc[3]], " @ ")
			if len(price) >= len(purchasedFor) && strings.EqualFold(price[:len(purchasedFor)], purchasedFor) {
				price = price[len(purchasedFor):]
			}
			row.cents, row.hasPrice = parsePrice(price)
			row.merchant = strings.TrimSpace(merchant)
			row.name = strings.TrimSpace(row.name[:loc[0]])
		}
		if row.name != "" {
			list.rows = append(list.rows, row)
		}
	}
	return list
}

package handlers

import (
	"regexp"
	"strings"
)

// PCPartPicker shows lists only to signed-in users, so Racket can't fetch
// them. Instead the user copies a list's plain-text markup (Markup, then the
// Text tab, on the list page) and pastes it. It looks like this:
//
//	PCPartPicker Part List: https://pcpartpicker.com/list/Kd3LPf
//
//	CPU: AMD Ryzen 7 9800X3D 4.7 GHz 8-Core Processor  ($444.00 @ Amazon)
//	Memory: Corsair Vengeance RGB 32 GB (2 x 16 GB) DDR5-6000 CL36 Memory  ($579.99 @ Corsair)
//	Total: $3965.72
//	Prices include shipping, taxes, and discounts when available
//	Generated by PCPartPicker 2026-10-02 21:28 EDT-0400

var (
	// pcppURLRe finds a pcpartpicker.com URL, on any regional subdomain.
	pcppURLRe = regexp.MustCompile(`https?://(?:[a-z0-9-]+\.)?pcpartpicker\.com/[^\s()<>]+`)

	// pcppPartRe splits a part line into its type and the rest. Types are
	// words like "CPU Cooler" or "Video Card". The colon must be followed by
	// a space, so "Generated by PCPartPicker 2026-10-02 21:28" isn't a part.
	pcppPartRe = regexp.MustCompile(`^([A-Za-z][A-Za-z0-9 /&+-]*):\s+(.+)$`)

	// pcppPriceRe matches the trailing price, "($444.00 @ Amazon)" or
	// "(Purchased For $50.00)". A name's own brackets, like "(2 x 16 GB)",
	// have no currency symbol and stay part of the name.
	pcppPriceRe = regexp.MustCompile(`\s*\(([^()]*[$£€¥₹][^()]*)\)$`)
)

// pcppSummaryLines are the "Label: value" lines in a list that aren't parts.
var pcppSummaryLines = map[string]bool{
	"total":           true,
	"base total":      true,
	"mail-in rebates": true,
	"promo discounts": true,
	"shipping":        true,
	"tax":             true,
}

// pcppList is a pasted PCPartPicker list: the list's URL from its first
// line ("" if the paste didn't include it) and its parts, in order.
type pcppList struct {
	url  string
	rows []csvRow
}

// parsePCPPText parses PCPartPicker's plain-text list markup. Lines it
// doesn't recognize are skipped, so a paste with extra text still works.
func parsePCPPText(text string) pcppList {
	var list pcppList
	for line := range strings.Lines(text) {
		line = strings.TrimSpace(line)
		if strings.HasPrefix(strings.ToLower(line), "pcpartpicker part list") {
			list.url = pcppURLRe.FindString(line)
			continue
		}
		m := pcppPartRe.FindStringSubmatch(line)
		if m == nil || pcppSummaryLines[strings.ToLower(m[1])] {
			continue
		}
		row := csvRow{category: m[1], name: m[2]}
		if loc := pcppPriceRe.FindStringSubmatchIndex(row.name); loc != nil {
			price, merchant, _ := strings.Cut(row.name[loc[2]:loc[3]], " @ ")
			row.price, row.hasPrice = parsePrice(price)
			row.merchant = strings.TrimSpace(merchant)
			row.name = strings.TrimSpace(row.name[:loc[0]])
		}
		if row.name != "" {
			list.rows = append(list.rows, row)
		}
	}
	return list
}

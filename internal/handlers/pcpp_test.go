const ramKit = "Corsair Vengeance RGB 32 GB (2 x 16 GB) DDR5-6000 CL36 Memory"

func TestParsePCPPText(t *testing.T) {
	list := parsePCPPText(samplePaste)
	if list.url != "https://pcpartpicker.com/list/Kd3LPf" {
		t.Errorf("url = %q", list.url)
	}
	if len(list.rows) != 11 {
		t.Fatalf("got %d parts, want 11 (Total and the footer aren't parts): %+v", len(list.rows), list.rows)
	}
	want := map[int]csvRow{
		0: {
			category: cpu, name: "AMD Ryzen 7 9800X3D 4.7 GHz 8-Core Processor",
			price: 444, hasPrice: true, merchant: "Amazon",
		},
		3: {category: "Memory", name: ramKit, price: 579.99, hasPrice: true, merchant: "Corsair"},
		10: {
			category: "Power Supply", name: "MSI MAG A750GL PCIE5 750 W 80+ Gold Certified Fully Modular ATX Power Supply",
			price: 79.99, hasPrice: true, merchant: "Newegg",
		},
	}
	for i, w := range want {
		if got := list.rows[i]; got != w {
			t.Errorf("row %d = %+v, want %+v", i, got, w)
		}
	}
}

func TestParsePCPPText_Variants(t *testing.T) {
	tests := []struct {
		name string
		line string
		want csvRow
	}{
		{"no price", "Case: Fractal Design North ATX Mid Tower Case",
			csvRow{category: "Case", name: "Fractal Design North ATX Mid Tower Case"}},
		{"name ends in brackets, no price", "Memory: Corsair Vengeance 32 GB (2 x 16 GB)",
			csvRow{category: "Memory", name: "Corsair Vengeance 32 GB (2 x 16 GB)"}},
		{"purchased price", "Storage: Samsung 990 Pro 2 TB  (Purchased For $120.00)",
			csvRow{category: "Storage", name: "Samsung 990 Pro 2 TB", price: 120, hasPrice: true}},
		{"thousands separator", "Video Card: Radeon RX 9070 XT  ($1,049.99 @ Amazon)",
			csvRow{category: "Video Card", name: "Radeon RX 9070 XT", price: 1049.99, hasPrice: true, merchant: "Amazon"}},
		{"regional currency", "CPU: Ryzen 5 7600  (£179.99 @ Scan)",
			csvRow{category: cpu, name: "Ryzen 5 7600", price: 179.99, hasPrice: true, merchant: "Scan"}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			list := parsePCPPText(tt.line)
			if len(list.rows) != 1 || list.rows[0] != tt.want {
				t.Errorf("rows = %+v, want [%+v]", list.rows, tt.want)
			}
		})
	}
}

func TestParsePCPPText_NotAList(t *testing.T) {
	for _, text := range []string{
		"",
		"https://pcpartpicker.com/list/Kd3LPf",
		"Total: $3965.72\nMail-in rebates: -$20.00\nGenerated by PCPartPicker 2026-10-02 21:28 EDT-0400",
	} {
		if list := parsePCPPText(text); len(list.rows) != 0 {
			t.Errorf("parsePCPPText(%q) found parts %+v", text, list.rows)
		}
	}
}

func TestImportPaste(t *testing.T) {
	app := newTestApp(t)
	alice := app.login("alice")

	rr := app.post(alice, "/import", url.Values{
		"pcpartpicker_text": {samplePaste},
		"machine_name":      {"test"},
		"wanted":            {"on"},
	})
	assertStatus(t, rr, http.StatusSeeOther)

	parts := app.ownedParts("alice")
	if len(parts) != 11 {
		t.Fatalf("imported %d parts, want 11", len(parts))
	}
	for _, p := range parts {
		if p.Status != partWanted || p.SourceUrl.String != "https://pcpartpicker.com/list/Kd3LPf" || !p.PriceCheckedAt.Valid {
			t.Errorf("part %q = %s from %q (checked %v), want wanted, from the list, checked",
				p.Name, p.Status, p.SourceUrl.String, p.PriceCheckedAt.Valid)
		}
	}

	machines, err := app.queries.ListMachines(t.Context())
	if err != nil {
		t.Fatal(err)
	}
	slots := app.slots(machines[0].Machine.ID)
	// The four RAM kits fill the two default RAM slots and get two more.
	if got := slotContents(slots)[ram]; len(got) != 4 {
		t.Errorf("RAM slots hold %v, want all four kits", got)
	}
	for _, c := range []string{"CPU Cooler", gpu, "PSU"} {
		if len(slotContents(slots)[c]) != 1 {
			t.Errorf("%s slot holds %v, want one part", c, slotContents(slots)[c])
		}
	}
	if machines[0].PartsTotalCents != 396572 {
		t.Errorf("machine total = %d cents, want the list's $3965.72", machines[0].PartsTotalCents)
	}
}

